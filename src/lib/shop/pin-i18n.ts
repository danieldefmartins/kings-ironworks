export const PIN_STRINGS = STR;

export function pint(lang: string | null | undefined, key: string, vars?: Record<string, string | number>): string {
  let s = STR[asLang(lang)][key] ?? STR.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  return s;
}
