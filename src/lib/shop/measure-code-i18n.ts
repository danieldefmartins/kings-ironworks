export function ct(lang: string | null | undefined, key: string): string {
  const l = asL(lang);
  return STR[l][key] ?? STR.en[key] ?? key;
}

function fmt(n: number, unit: CodeResult["unit"]): string {
  if (unit === "ratio") return n <= 0 ? "0" : `1:${(1 / n).toFixed(1).replace(/\.0$/, "")}`;
  if (unit === "ft") return `${n.toFixed(1).replace(/\.0$/, "")} ft`;
  return formatIn(n);
}

/** "≤ 7 3/4"", "≥ 36"", "34"–38"" — the limit as the crew reads it. */
export function codeLimitText(r: CodeResult): string {
  if (r.op === "check" || r.limit === null) return r.rule === "pool_latch" && r.limit ? `≥ ${formatIn(r.limit)}` : "—";
  if (r.op === "range") return `${fmt(r.limit, r.unit)}–${fmt(r.limit2 ?? r.limit, r.unit)}`;
  // Ratios read naturally as "≤ 1:12". For trigger rules (a guard / ladder is
  // required ABOVE the limit) the limit is shown as the trigger.
  if (r.rule === "guard_required" || r.rule === "well_ladder" || r.rule === "fixed_ladder") return `> ${fmt(r.limit, r.unit)}`;
  return `${r.op === "max" ? "≤" : "≥"} ${fmt(r.limit, r.unit)}`;
}

export function codeActualText(lang: string, r: CodeResult): string {
  if (r.actual === null) {
    if (r.rule === "pool_swing") return r.level === "green" ? ct(lang, "yes") : ct(lang, "no");
    if (r.rule === "handrail_required") return r.level === "green" ? ct(lang, "yes") : ct(lang, "no");
    return "—";
  }
  return fmt(r.actual, r.unit);
}

export function codeRuleLabel(lang: string, r: CodeResult): string {
  return `${ct(lang, `code_${r.rule}`)}${r.detail ? ` ${r.detail}` : ""}`;
}
