export function mt(lang: string | undefined | null, key: string): string {
  const l = asLang(lang);
  return STR[l][key] || STR.en[key] || key;
}

export function shapeLabel(lang: string | undefined | null, shape: MeasureShape): string {
  return mt(lang, `shape_${shape}`);
}

