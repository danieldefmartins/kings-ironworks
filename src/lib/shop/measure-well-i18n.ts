/**
 * The words for the ends of a run or a wall. The front run and the far / house
 * walls go left to right seen from outside; a side goes from the house out.
 */
export function wellAlongKeys(side: boolean, what: "gate" | "ladder"): { start: string; center: string; end: string } {
  if (what === "gate") return side ? { start: "wellAt_house", center: "wellAt_center", end: "wellAt_corner" } : { start: "wellAt_left", center: "wellAt_center", end: "wellAt_right" };
  return side ? { start: "wellLadAt_house", center: "wellAt_center", end: "wellLadAt_far" } : { start: "wellLadAt_left", center: "wellAt_center", end: "wellLadAt_right" };
}

/**
 * Hinge side is stored as seen from outside, facing the gate. On a side run
 * that is said by what it is next to: on the left run the house is on the
 * viewer's left, on the right run it is on the right.
 */
export function wellHingeKeys(run: string): { left: string; right: string } {
  if (run === "left") return { left: "wellHinge_house", right: "wellHinge_front" };
  if (run === "right") return { left: "wellHinge_front", right: "wellHinge_house" };
  return { left: "wellHingeLeft", right: "wellHingeRight" };
}
