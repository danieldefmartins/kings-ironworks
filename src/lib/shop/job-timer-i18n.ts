export function jt(lang: string | undefined | null, key: string, vars?: Record<string, string | number>): string {
  let s = STR[asLang(lang)][key] ?? STR.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  return s;
}

