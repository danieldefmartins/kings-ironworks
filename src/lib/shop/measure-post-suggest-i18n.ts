export const POST_SUGGEST_STRINGS = TABLE;

export function ps(lang: string, key: Key, vars: Record<string, string | number> = {}): string {
  const table = lang === "pt" ? PT : lang === "es" ? ES : EN;
  return (table[key] ?? EN[key]).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
