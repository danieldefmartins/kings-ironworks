export function t(
  lang: string | undefined | null,
  key: string,
  vars?: Record<string, string | number>
): string {
  const l = asLang(lang);
  let s = STR[l][key] ?? STR.en[key] ?? key;
  if (vars) {
    for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  }
  return s;
}

